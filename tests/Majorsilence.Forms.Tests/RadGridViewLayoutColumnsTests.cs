using System.Data;
using System.Linq;
using Majorsilence.Forms.Telerik;
using Xunit;

namespace Majorsilence.Forms.Tests
{
    // A Telerik layout is the grid's column set, and binding keeps the columns a grid already has. Measured on
    // Telerik (UI for WinForms 2026.2.520) with the layout below, saved from a grid bound to Id, Code, Desc,
    // Amt and X with Amt moved first, Id hidden, Code captioned and Desc 222 wide:
    //  - loaded into an unbound grid it creates those five columns, and binding a source with Id, Code, Desc,
    //    Amt and Extra then keeps Amt, Id, Code, Desc in that order, drops X and generates no Extra;
    //  - loaded into a grid bound to that source it removes Extra and adds an empty X;
    //  - a column the app added survives a bind its field is not in; one generated is removed;
    //  - rebinding to a different schema appends that schema's new fields, and to the same one, none.
    public class RadGridViewLayoutColumnsTests
    {
        private const string Layout =
            "<RadGridView TabIndex=\"1\"><MasterTemplate><Columns>" +
            "<Telerik.WinControls.UI.GridViewDecimalColumn FieldName=\"Amt\" Name=\"Amt\" IsAutoGenerated=\"True\" IsVisible=\"True\" HeaderText=\"Amt\" />" +
            "<Telerik.WinControls.UI.GridViewTextBoxColumn FieldName=\"Id\" Name=\"Id\" IsAutoGenerated=\"True\" IsVisible=\"False\" HeaderText=\"Id\" />" +
            "<Telerik.WinControls.UI.GridViewTextBoxColumn FieldName=\"Code\" Name=\"Code\" IsAutoGenerated=\"True\" IsVisible=\"True\" HeaderText=\"The Code\" />" +
            "<Telerik.WinControls.UI.GridViewTextBoxColumn Width=\"222\" FieldName=\"Desc\" Name=\"Desc\" IsAutoGenerated=\"True\" IsVisible=\"True\" HeaderText=\"Desc\" />" +
            "<Telerik.WinControls.UI.GridViewTextBoxColumn FieldName=\"X\" Name=\"X\" IsAutoGenerated=\"True\" IsVisible=\"True\" HeaderText=\"X\" />" +
            "</Columns></MasterTemplate></RadGridView>";

        private static DataTable Table (params string[] columns)
        {
            var table = new DataTable { TableName = "T" };
            foreach (var c in columns)
                table.Columns.Add (c, c == "Amt" ? typeof (decimal) : typeof (string));
            table.Rows.Add (columns.Select (c => c == "Amt" ? (object) 1.5m : c + "1").ToArray ());
            return table;
        }

        private static string[] Names (RadGridView grid) => grid.Columns.Select (c => c.Name).ToArray ();

        private static object? Value (RadGridView grid, string column) => grid.Rows[0].Cells[column].Value;

        [Fact]
        public void A_layout_loaded_into_an_unbound_grid_creates_its_columns ()
        {
            using var grid = new RadGridView ();

            grid.LoadLayoutFromString (Layout);

            Assert.Equal (new[] { "Amt", "Id", "Code", "Desc", "X" }, Names (grid));
            Assert.IsType<GridViewDecimalColumn> (grid.Columns["Amt"]);
            Assert.False (grid.Columns["Id"]!.IsVisible);
            Assert.Equal ("The Code", grid.Columns["Code"]!.HeaderText);
            Assert.Equal (222, grid.Columns["Desc"]!.Width);
            Assert.Equal (0, grid.Rows.Count);
        }

        [Fact]
        public void Binding_after_the_layout_keeps_its_columns_and_drops_the_missing_generated_ones ()
        {
            using var grid = new RadGridView ();
            grid.LoadLayoutFromString (Layout);

            grid.DataSource = Table ("Id", "Code", "Desc", "Amt", "Extra");

            Assert.Equal (new[] { "Amt", "Id", "Code", "Desc" }, Names (grid));
            Assert.Equal (1.5m, Value (grid, "Amt"));
            Assert.Equal ("Code1", Value (grid, "Code"));
            Assert.Equal ("Desc1", Value (grid, "Desc"));
            Assert.Equal (222, grid.Columns["Desc"]!.Width);
            Assert.Equal ("The Code", grid.Columns["Code"]!.HeaderText);
        }

        [Fact]
        public void Binding_a_DataSet_member_after_the_layout_keeps_its_columns ()
        {
            using var grid = new RadGridView ();
            grid.LoadLayoutFromString (Layout);
            var data = new DataSet ();
            data.Tables.Add (Table ("Id", "Code", "Desc", "Amt", "Extra"));

            grid.DataSource = new BindingSource { DataSource = data, DataMember = "T" };

            Assert.Equal (new[] { "Amt", "Id", "Code", "Desc" }, Names (grid));
            Assert.Equal ("Id1", Value (grid, "Id"));
        }

        [Fact]
        public void A_layout_loaded_into_a_bound_grid_replaces_its_column_set ()
        {
            using var grid = new RadGridView { DataSource = Table ("Id", "Code", "Desc", "Amt", "Extra") };

            grid.LoadLayoutFromString (Layout);

            Assert.Equal (new[] { "Amt", "Id", "Code", "Desc", "X" }, Names (grid));
            Assert.Equal (1.5m, Value (grid, "Amt"));
            Assert.Equal ("Desc1", Value (grid, "Desc"));
            Assert.Null (Value (grid, "X"));
        }

        [Fact]
        public void An_added_column_survives_a_bind_without_its_field ()
        {
            using var grid = new RadGridView ();
            grid.Columns.Add (new GridViewTextBoxColumn ("Code") { Width = 66 });
            grid.Columns.Add (new GridViewTextBoxColumn ("Manual"));

            grid.DataSource = Table ("Id", "Code", "Desc");

            Assert.Equal (new[] { "Code", "Manual" }, Names (grid));
            Assert.Equal (66, grid.Columns["Code"]!.Width);
            Assert.Equal ("Code1", Value (grid, "Code"));
        }

        [Fact]
        public void Rebinding_appends_the_fields_of_a_new_schema_only ()
        {
            using var grid = new RadGridView ();
            grid.LoadLayoutFromString (Layout);
            grid.DataSource = Table ("Id", "Code", "Desc", "Amt", "Extra");

            grid.DataSource = Table ("Id", "Code", "Desc", "Amt", "Extra");
            Assert.Equal (new[] { "Amt", "Id", "Code", "Desc" }, Names (grid));

            grid.DataSource = Table ("Code", "Amt", "Extra", "Id");
            Assert.Equal (new[] { "Amt", "Id", "Code", "Extra" }, Names (grid));
            Assert.Equal ("Extra1", Value (grid, "Extra"));
        }

        [Fact]
        public void A_grid_without_columns_generates_them_in_the_source_order ()
        {
            using var grid = new RadGridView ();
            grid.LoadLayoutFromString (Layout);
            grid.DataSource = new DataTable ();
            Assert.Empty (grid.Columns);

            grid.DataSource = Table ("Id", "Code", "Desc", "Amt", "Extra");

            Assert.Equal (new[] { "Id", "Code", "Desc", "Amt", "Extra" }, Names (grid));
            Assert.True (grid.Columns["Id"]!.IsVisible);
        }
    }
}
