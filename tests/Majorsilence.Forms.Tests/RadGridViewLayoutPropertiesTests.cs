using System.Data;
using System.Linq;
using Majorsilence.Forms.Telerik;
using Xunit;

namespace Majorsilence.Forms.Tests
{
    // A layout saved by Telerik's grid carries each property that differs from its default, on the grid, its
    // MasterTemplate and its columns, and Telerik's LoadLayout sets every one. Measured on Telerik (UI for WinForms
    // 2026.2.520) with a grid at Microsoft Sans Serif 12pt loading a layout like the one below:
    //  - the grid took Font 8pt, AutoSizeRows, ReadOnly and TabStop False; without the Font attribute it kept 12pt;
    //  - the template took SelectionMode CellSelect, AllowAddNewRow False and AutoExpandGroups True;
    //  - the columns took HeaderTextAlignment, TextAlignment, FormatString and DataType;
    //  - a column's conditional-formatting rules were the layout's, any it had before removed, each rule with its
    //    TValue1, colors (a name, "r, g, b", or "" for none) and ConditionType Equal, the default;
    //  - the template's sort descriptors replaced the grid's, and a layout without any kept the grid's.
    public class RadGridViewLayoutPropertiesTests
    {
        private const string Layout =
            "<RadGridView AutoSizeRows=\"True\" ReadOnly=\"True\" Font=\"Microsoft Sans Serif, 8pt\" TabIndex=\"0\" TabStop=\"False\">" +
            "<MasterTemplate SelectionMode=\"CellSelect\" AllowAddNewRow=\"False\" AutoExpandGroups=\"True\"><Columns>" +
            "<Telerik.WinControls.UI.GridViewTextBoxColumn Width=\"143\" FieldName=\"Code\" Name=\"Code\" IsAutoGenerated=\"True\" IsVisible=\"True\" HeaderText=\"Code\" HeaderTextAlignment=\"MiddleLeft\" />" +
            "<Telerik.WinControls.UI.GridViewDecimalColumn FormatString=\"{0:#,###,0.00}\" Width=\"109\" FieldName=\"Amt\" Name=\"Amt\" IsAutoGenerated=\"True\" IsVisible=\"True\" HeaderText=\"Amount\" HeaderTextAlignment=\"MiddleLeft\" TextAlignment=\"MiddleRight\" />" +
            "<Telerik.WinControls.UI.GridViewTextBoxColumn DataType=\"System.Int32\" Width=\"70\" FieldName=\"Status\" Name=\"Status\" IsAutoGenerated=\"True\" IsVisible=\"True\" HeaderText=\"Status\" HeaderTextAlignment=\"MiddleLeft\">" +
            "<ConditionalFormattingObjectList>" +
            "<Telerik.WinControls.UI.ConditionalFormattingObject TValue1=\"1\" CellForeColor=\"\" CellBackColor=\"\" RowForeColor=\"\" RowBackColor=\"BurlyWood\" Name=\"Status\" ApplyToRow=\"True\" />" +
            "<Telerik.WinControls.UI.ConditionalFormattingObject TValue1=\"2\" CellForeColor=\"\" CellBackColor=\"\" RowForeColor=\"\" RowBackColor=\"255, 192, 255\" Name=\"Status\" ApplyToRow=\"True\" />" +
            "</ConditionalFormattingObjectList>" +
            "</Telerik.WinControls.UI.GridViewTextBoxColumn>" +
            "</Columns><SortDescriptors><Telerik.WinControls.Data.SortDescriptor PropertyName=\"Code\" /></SortDescriptors>" +
            "<ViewDefinition xsi:type=\"Telerik.WinControls.UI.TableViewDefinition\" xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\" />" +
            "</MasterTemplate></RadGridView>";

        private static RadGridView Grid () => new () { Font = new Majorsilence.Forms.Drawing.Font ("Microsoft Sans Serif", 12f) };

        [Fact]
        public void The_layout_sets_the_grids_own_properties ()
        {
            using var grid = Grid ();

            grid.LoadLayoutFromString (Layout);

            Assert.Equal (8f, grid.Font.Size);
            Assert.True (grid.AutoSizeRows);
            Assert.True (grid.ReadOnly);
            Assert.False (grid.TabStop);
        }

        [Fact]
        public void A_property_the_layout_leaves_out_keeps_its_value ()
        {
            using var grid = Grid ();

            grid.LoadLayoutFromString (Layout.Replace (" Font=\"Microsoft Sans Serif, 8pt\"", ""));

            Assert.Equal (12f, grid.Font.Size);
        }

        [Fact]
        public void The_layout_sets_the_templates_properties ()
        {
            using var grid = Grid ();

            grid.LoadLayoutFromString (Layout);

            Assert.Equal (GridViewSelectionMode.CellSelect, grid.SelectionMode);
            Assert.False (grid.MasterTemplate.AllowAddNewRow);
            Assert.False (grid.AllowAddNewRow);
            Assert.True (grid.MasterTemplate.AutoExpandGroups);
        }

        [Fact]
        public void The_layout_sets_each_columns_properties ()
        {
            using var grid = Grid ();

            grid.LoadLayoutFromString (Layout);

            var code = (GridViewColumn) grid.Columns["Code"]!;
            var amount = (GridViewDataColumn) grid.Columns["Amt"]!;
            var status = (GridViewDataColumn) grid.Columns["Status"]!;
            Assert.Equal (ContentAlignment.MiddleLeft, code.HeaderTextAlignment);
            Assert.Equal (ContentAlignment.MiddleRight, ((GridViewColumn) amount).TextAlignment);
            Assert.Equal ("{0:#,###,0.00}", amount.FormatString);
            Assert.Equal (typeof (int), status.DataType);
        }

        [Fact]
        public void A_columns_rules_are_the_layouts ()
        {
            using var grid = Grid ();
            grid.LoadLayoutFromString (Layout);
            var status = (GridViewColumn) grid.Columns["Status"]!;
            status.ConditionalFormattingObjectList.Add (new ConditionalFormattingObject ("extra", ConditionTypes.Equal, "9"));

            grid.LoadLayoutFromString (Layout);

            var rules = status.ConditionalFormattingObjectList;
            Assert.Equal (new[] { "1", "2" }, rules.Select (r => r.TValue1));
            Assert.Equal (System.Drawing.Color.BurlyWood, rules[0].RowBackColor);
            Assert.Equal (System.Drawing.Color.FromArgb (255, 192, 255).ToArgb (), rules[1].RowBackColor.ToArgb ());
            Assert.Equal (System.Drawing.Color.Empty, rules[0].CellBackColor);
            Assert.Equal (ConditionTypes.Equal, rules[0].ConditionType);
            Assert.Equal ("Status", rules[0].Name);
        }

        [Fact]
        public void The_layouts_sort_replaces_the_grids_and_none_keeps_it ()
        {
            using var grid = Grid ();
            grid.LoadLayoutFromString (Layout);
            Assert.Equal (new[] { "Code" }, grid.SortDescriptors.Select (s => s.PropertyName));

            grid.SortDescriptors.Clear ();
            grid.SortDescriptors.Add (new SortDescriptor ("Amt", System.ComponentModel.ListSortDirection.Descending));
            grid.LoadLayoutFromString (Layout.Replace ("<SortDescriptors><Telerik.WinControls.Data.SortDescriptor PropertyName=\"Code\" /></SortDescriptors>", ""));

            Assert.Equal (new[] { "Amt" }, grid.SortDescriptors.Select (s => s.PropertyName));
        }
    }
}
